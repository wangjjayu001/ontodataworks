"""Generate module entrypoints and GitHub path labels from one manifest."""
from __future__ import annotations

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def generated_files():
    modules = json.loads((ROOT / "project/modules.json").read_text(encoding="utf-8"))["modules"]
    labels = ["# Generated by scripts/sync_modules.py; edit project/modules.json.\n"]
    result = {}
    for module in modules:
        mid = module["id"]
        patterns = list(dict.fromkeys(module["paths"] + module["tests"] + [f"modules/{mid}/**"]))
        labels.extend([f'"module:{mid}":', "  - changed-files:", "      - any-glob-to-any-file:"])
        labels.extend("          - " + json.dumps(pattern, ensure_ascii=False) for pattern in patterns)
        lines = [f'# {module["title"]}', "", "<!-- Generated by scripts/sync_modules.py; edit project/modules.json. -->", "",
                 module["summary"], "", f'PR scope：`{mid}`；GitHub 标签：`module:{mid}`。', "", "## 代码归属", ""]
        lines.extend(f"- `{pattern}`" for pattern in module["paths"])
        lines.extend(["", "## 现有验证入口", ""])
        lines.extend(f"- `{pattern}`" for pattern in module["tests"])
        lines.extend(["", "## 接口与评审边界", "", module["contracts"], "",
                      "在线 validate 脚本依赖特定测试数据，不能直接用于空库或生产。运行方式见[测试规范](../../docs/maintenance/testing.md)。",
                      "", "[完整模块表](../../docs/maintenance/modules.md) · [贡献规范](../../CONTRIBUTING.md)", ""])
        result[ROOT / f"modules/{mid}/README.md"] = "\n".join(lines)
    result[ROOT / ".github/labeler.yml"] = "\n".join(labels) + "\n"
    return result


def sync(check=False):
    stale = []
    for path, content in generated_files().items():
        if not path.exists() or path.read_text(encoding="utf-8") != content:
            stale.append(path.relative_to(ROOT).as_posix())
            if not check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(content, encoding="utf-8", newline="\n")
    if check and stale:
        raise SystemExit("Run python scripts/sync_modules.py; stale: " + ", ".join(stale))
    return stale


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    changed = sync(args.check)
    print(f"Module outputs {'verified' if args.check else 'generated'} ({len(changed)} changed).")
